#!/usr/bin/env node
// Regenerates the dot-matrix land mask used by the public status page map.
//
//   node scripts/generate-world-mask.mjs [--width 90] [--height 35]
//                                         [--lat-max 83] [--lat-min -56] [--out <path>]
//
// Source: Natural Earth 1:110m "land" polygons, which are public domain
// (naturalearthdata.com terms of use). We fetch the GeoJSON, then rasterize it
// onto an equirectangular grid: a cell is land when its centre point falls
// inside any land ring, tested with even-odd ray casting. Holes in a polygon
// (lakes, inland seas) are handled by the same even-odd rule, so the Caspian
// reads as sea without special casing.
//
// The latitude range is cropped to the populated world by default. Antarctica
// spans every column at the bottom of a full-range grid, which reads as a heavy
// bar rather than a quiet texture, and the empty Arctic ocean wastes rows.
//
// The output is committed so the page has no build-time or run-time network
// dependency. Rerun this only to change the resolution or refresh the source.

import { writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const SOURCE =
  "https://raw.githubusercontent.com/nvkelso/natural-earth-vector/master/geojson/ne_110m_land.geojson";

const here = dirname(fileURLToPath(import.meta.url));
const args = process.argv.slice(2);

function flag(name, fallback) {
  const index = args.indexOf(`--${name}`);
  return index === -1 ? fallback : args[index + 1];
}

const width = Number(flag("width", 90));
const height = Number(flag("height", 35));
const latMax = Number(flag("lat-max", 83));
const latMin = Number(flag("lat-min", -56));
const outPath = resolve(here, flag("out", "../web/console/lib/worldMask.ts"));

// Even-odd ray casting. `ring` is [[lon, lat], ...].
function pointInRing(lon, lat, ring) {
  let inside = false;
  for (let i = 0, j = ring.length - 1; i < ring.length; j = i++) {
    const [xi, yi] = ring[i];
    const [xj, yj] = ring[j];
    const straddles = yi > lat !== yj > lat;
    if (straddles && lon < ((xj - xi) * (lat - yi)) / (yj - yi) + xi) {
      inside = !inside;
    }
  }
  return inside;
}

// A polygon is land when the point is inside an odd number of its rings, which
// makes the outer ring land and any hole ring sea.
function pointInPolygon(lon, lat, rings) {
  let crossings = 0;
  for (const ring of rings) {
    if (pointInRing(lon, lat, ring)) {
      crossings++;
    }
  }
  return crossings % 2 === 1;
}

const response = await fetch(SOURCE);
if (!response.ok) {
  console.error(`fetch ${SOURCE} failed: ${response.status}`);
  process.exit(1);
}
const geojson = await response.json();

const polygons = [];
for (const feature of geojson.features) {
  const geometry = feature.geometry;
  if (geometry.type === "Polygon") {
    polygons.push(geometry.coordinates);
  } else if (geometry.type === "MultiPolygon") {
    for (const part of geometry.coordinates) {
      polygons.push(part);
    }
  }
}

const rows = [];
for (let row = 0; row < height; row++) {
  // Sample each cell at its centre.
  const lat = latMax - ((row + 0.5) / height) * (latMax - latMin);
  let line = "";
  for (let col = 0; col < width; col++) {
    const lon = ((col + 0.5) / width) * 360 - 180;
    let land = false;
    for (const rings of polygons) {
      if (pointInPolygon(lon, lat, rings)) {
        land = true;
        break;
      }
    }
    line += land ? "1" : "0";
  }
  rows.push(line);
}

const landCells = rows.join("").split("").filter((cell) => cell === "1").length;

const file = `// Generated by scripts/generate-world-mask.mjs — do not edit by hand.
// Source: Natural Earth 1:110m land polygons (public domain), rasterized onto
// an equirectangular ${width}x${height} grid by sampling each cell centre.
// Latitude runs ${latMax} (row 0) down to ${latMin}; longitude -180 (column 0)
// to 180. "1" is land, "0" is sea.

export const WORLD_MASK_WIDTH = ${width};
export const WORLD_MASK_HEIGHT = ${height};
export const WORLD_MASK_LAT_MAX = ${latMax};
export const WORLD_MASK_LAT_MIN = ${latMin};

export const WORLD_MASK: readonly string[] = [
${rows.map((line) => `  "${line}"`).join(",\n")}
];
`;

writeFileSync(outPath, file);
console.log(`wrote ${outPath} (${width}x${height}, ${landCells} land cells)`);
